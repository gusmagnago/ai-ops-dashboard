#!/usr/bin/env node
// Sync shared AI-context notes from Obsidian into a compact index, then write
// that index into a managed block of CLAUDE.md / AGENTS.md across configured
// targets. This is "Claude teaches Codex": both assistants read the same
// pointer list, while the heavy notes stay in the vault as on-demand files.
//
// The index stores only: title, one-line summary, area, status, and the vault
// path to read on demand. It never copies note bodies or secrets into repos.
//
// Usage:
//   node scripts/sync-context.mjs              # write to all syncTargets
//   node scripts/sync-context.mjs --dry-run    # print the block, write nothing
//   node scripts/sync-context.mjs --check      # exit 1 if any target is stale

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, isAbsolute, basename } from 'node:path';
import { argv, cwd, exit } from 'node:process';
import { loadConfig, contextDir } from './lib/context-config.mjs';

const args = argv.slice(2);
const dryRun = args.includes('--dry-run');
const checkOnly = args.includes('--check');

const START = '<!-- ai-ops:context:start -->';
const END = '<!-- ai-ops:context:end -->';

const config = loadConfig();

if (!config.vaultPath) {
  console.error('No vaultPath configured. Run `npm run setup` or set AI_OPS_VAULT_PATH.');
  exit(1);
}

const dir = contextDir(config);
if (!existsSync(dir)) {
  console.error(`AI-context directory not found: ${dir}`);
  console.error('Check vaultPath / aiContextDir in ai-ops.config.json.');
  exit(1);
}

// --- parse a note into an index entry --------------------------------------

const parseFrontmatter = (raw) => {
  const match = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return { fm: {}, body: raw };
  const fm = {};
  for (const line of match[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) fm[kv[1].trim()] = kv[2].trim();
  }
  return { fm, body: raw.slice(match[0].length) };
};

const firstParagraph = (body) => {
  const lines = body.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (trimmed.startsWith('#')) continue;
    if (trimmed.startsWith('---')) continue;
    if (trimmed.startsWith('[[') && trimmed.endsWith(']]')) continue;
    // Strip a leading list marker so bullet-first notes read as a phrase.
    return trimmed.replace(/^[-*+]\s+/, '').replace(/^\d+\.\s+/, '').replace(/\s+/g, ' ');
  }
  return '';
};

const truncate = (text, max = 140) =>
  text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`;

const titleFrom = (body, file) => {
  const heading = body.match(/^#\s+(.+)$/m);
  if (heading) return heading[1].trim();
  return basename(file, '.md');
};

const entries = readdirSync(dir)
  .filter((file) => file.endsWith('.md'))
  .map((file) => {
    const raw = readFileSync(resolve(dir, file), 'utf-8');
    const { fm, body } = parseFrontmatter(raw);
    return {
      file,
      title: titleFrom(body, file),
      area: fm.area || 'general',
      status: fm.status || '',
      type: fm.type || '',
      summary: truncate(firstParagraph(body)),
    };
  })
  // Only index notes explicitly marked as shared AI context.
  .filter((entry) => entry.type === 'ai-context')
  .filter((entry) => !config.excludeAreas.includes(entry.area))
  .sort((a, b) => a.area.localeCompare(b.area) || a.title.localeCompare(b.title));

if (entries.length === 0) {
  console.warn('No notes with `type: ai-context` found to index.');
}

// --- render the managed block ----------------------------------------------

const renderBlock = () => {
  const relDir = config.aiContextDir;
  const assistants = config.providers
    .map((p) => (p === 'claude' ? 'Claude Code' : p === 'codex' ? 'Codex' : p))
    .join(' and ');

  const lines = [];
  lines.push(START);
  lines.push('## Shared AI Context (synced from Obsidian)');
  lines.push('');
  lines.push(
    `_Auto-generated by \`npm run sync\` in ai-ops-dashboard. Do not edit between markers. ${assistants} read this index; the full notes live in the vault and should be read on demand._`,
  );
  lines.push('');
  lines.push('```text');
  lines.push(config.vaultPath);
  lines.push('```');
  lines.push('');

  let currentArea = null;
  for (const entry of entries) {
    if (entry.area !== currentArea) {
      if (currentArea !== null) lines.push('');
      currentArea = entry.area;
      lines.push(`### ${currentArea}`);
      lines.push('');
    }
    const path = `${relDir}/${entry.file}`;
    const status = entry.status ? ` _(${entry.status})_` : '';
    lines.push(`- **${entry.title}**${status} — \`${path}\``);
    if (entry.summary) lines.push(`  ${entry.summary}`);
  }
  lines.push('');
  lines.push(`_Last synced: ${new Date().toISOString().slice(0, 10)} · ${entries.length} notes._`);
  lines.push(END);
  return lines.join('\n');
};

const block = renderBlock();

// --- apply to a target file -------------------------------------------------

// Returns { changed, content } without writing.
const applyToContent = (existing) => {
  if (existing.includes(START) && existing.includes(END)) {
    const before = existing.slice(0, existing.indexOf(START));
    const after = existing.slice(existing.indexOf(END) + END.length);
    const next = `${before}${block}${after}`;
    return { changed: stripDate(next) !== stripDate(existing), content: next };
  }
  // Append a fresh block, separated by a blank line.
  const sep = existing.endsWith('\n') ? '\n' : '\n\n';
  const next = `${existing}${sep}${block}\n`;
  return { changed: true, content: next };
};

// Ignore the "Last synced" date line when deciding if a write is meaningful,
// so re-running on the same notes is a no-op.
const stripDate = (text) => text.replace(/_Last synced: \d{4}-\d{2}-\d{2} · \d+ notes\._/g, '');

const resolveTarget = (target) => (isAbsolute(target) ? target : resolve(cwd(), target));

if (dryRun) {
  console.log(block);
  console.log(`\n--dry-run: indexed ${entries.length} notes, wrote nothing.`);
  exit(0);
}

let staleCount = 0;
let wroteCount = 0;
const missing = [];

for (const target of config.syncTargets) {
  const path = resolveTarget(target);
  if (!existsSync(path)) {
    missing.push(path);
    continue;
  }
  const existing = readFileSync(path, 'utf-8');
  const { changed, content } = applyToContent(existing);
  if (!changed) {
    console.log(`✓ up to date: ${target}`);
    continue;
  }
  if (checkOnly) {
    staleCount += 1;
    console.warn(`✗ stale: ${target}`);
    continue;
  }
  writeFileSync(path, content);
  wroteCount += 1;
  console.log(`✓ synced: ${target}`);
}

if (missing.length > 0) {
  console.warn(`\nSkipped missing targets:\n${missing.map((m) => `  - ${m}`).join('\n')}`);
}

if (checkOnly) {
  if (staleCount > 0) {
    console.error(`\n${staleCount} target(s) out of date. Run \`npm run sync\`.`);
    exit(1);
  }
  console.log('\nAll targets up to date.');
  exit(0);
}

console.log(`\nIndexed ${entries.length} notes → ${wroteCount} file(s) updated.`);
